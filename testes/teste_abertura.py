    J(pg, '__t.olhar(3, 1.6, -3)'); pg.keyboard.down('w'); time.sleep(2); pg.keyboard.up('w')
    print('andou para o mirante', J(pg, 'return __t.pos()'))
    J(pg, 'j.teleportar([2.8, 0, -2.6], 45)'); time.sleep(0.6); print('no mirante', J(pg, 'return __t.pos()'), pedido(pg))
    J(pg, "__t.olharId('mirante_ne', 0.8)"); time.sleep(1); pg.screenshot(path=F+'11_janela.png')
    print('depois do olhar:', pedido(pg))
    time.sleep(6); pg.screenshot(path=F+'12_titulo.png')
    print('caixas:', pular(pg, 80, lambda: (pedido(pg) or '').startswith('andar até')), pedido(pg))
    J(pg, 'j.teleportar([-1.0, 0, 2.2], 0)'); time.sleep(0.5)
    print('pegar:', pular(pg, 30, lambda: (pedido(pg) or '').startswith('pegar')), pedido(pg))
    c = J(pg, "return __t.olharId('caixa_teste_1')"); time.sleep(0.4)
    pg.screenshot(path=F+'13_mira_caixa.png')
    pg.mouse.click(640, 360, button='right'); time.sleep(0.5)
    print('segurando?', J(pg, "return j.seguraveis.get('caixa_teste_1').estado"), pedido(pg))
    pg.screenshot(path=F+'14_segurando.png')
    J(pg, '__t.olhar(-1.0, 0.5, 0.6)'); time.sleep(0.3)
    pg.mouse.click(640, 360, button='right'); time.sleep(1.5)
    print('soltou', J(pg, "const s = j.seguraveis.get('caixa_teste_1'); return [s.estado, s.inst.raiz.position.toArray().map(v=>+v.toFixed(2))]"))
