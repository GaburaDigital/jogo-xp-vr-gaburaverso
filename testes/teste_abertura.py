from base import *
with sync_playwright() as p:
    b, pg, erros = abrir(p)
    entrar_pc(pg)
    J(pg, "localStorage.clear();")
    # andar: W por 1,2 s
    J(pg, 'j.agir("qps")'); time.sleep(1.5); print('qps', pg.inner_text('.qps'))
    p0 = J(pg, 'return __t.pos()'); pg.keyboard.down('w'); time.sleep(1.2); pg.keyboard.up('w'); p1 = J(pg, 'return __t.pos()')
    print('andou', p0, '->', p1)
    print('esperando mirante:', pular(pg, 60, lambda: (pedido(pg) or '').startswith('chegar perto')), pedido(pg))
    pg.screenshot(path=F+'10_pede_mirante.png')
