    pg.keyboard.press('r'); time.sleep(0.3)
    J(pg, 'j.teleportar([0, 0, 0.8], 0)'); J(pg, '__t.olhar(0, 0.2, -6)'); time.sleep(2.5); pg.screenshot(path=F+'17_faixas.png')
    print('progresso', J(pg, 'return JSON.stringify(j.progresso)'))
    print('\n'.join(erros[:30]) or 'sem erros')
    b.close()
