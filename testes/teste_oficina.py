# Oficina no PC: pisar no posto, clicar na protoboard (câmera de foco), tentar as pegadinhas (não encaixam),
# encaixar os jumpers e o resistor, o LED primeiro ao contrário (encaixa mas não conta), virar com F e o circuito fecha.
from base import *

def pecas(pg): return {x['id']: x for x in J(pg, 'return j.pecasOficina()')}
def legenda(pg): return pg.evaluate("() => document.querySelector('.legenda')?.innerText || ''")

with sync_playwright() as p:
    b, pg, erros = abrir(p, 960, 600)
    entrar_pc(pg)
    J(pg, 'j.testeTempo.escala = 2')
    J(pg, "j.irPara('oficina_energia')"); time.sleep(2)
    J(pg, "__t.olharId('metalgabutron', 0.3)"); time.sleep(2); pg.screenshot(path=F + '50_oficina_metal.png')
    pular(pg, 90, lambda: (pedido(pg) or '').startswith('pisar'))
    print('pedido:', pedido(pg))
    J(pg, 'j.teleportar([16.4, 0, 0], -90)'); time.sleep(1)
    pular(pg, 40, lambda: (pedido(pg) or '').startswith('montar'))
    print('pedido:', pedido(pg))
    J(pg, "__t.olharId('protoboard')"); time.sleep(0.8)
    print('dica:', pg.inner_text('.dica') if pg.is_visible('.dica') else '-')
    pg.mouse.click(480, 300); time.sleep(2.5)
    print('foco:', J(pg, 'return j.oficina.focoPC'))
    pg.screenshot(path=F + '51_oficina_foco.png')
    alvos = J(pg, 'return j.alvosOficina()')
    def tela(x, y, z): return J(pg, f'return __t.noTela({x}, {y}, {z})')
    def arrastar(id, alvo_de, virar=0, foto=None):
        pc = pecas(pg)[id]['pos']; a = tela(pc[0], pc[1] + 0.03, pc[2])
        ax = alvos[alvo_de]; d = tela(ax[0] + 0.02, 1.0, ax[2] + 0.02)
        pg.mouse.move(*a); time.sleep(0.2); pg.mouse.down(); time.sleep(0.4)
        for _ in range(virar): pg.keyboard.press('f'); time.sleep(0.3)
        for i in range(1, 7): pg.mouse.move(a[0] + (d[0] - a[0]) * i / 6, a[1] + (d[1] - a[1]) * i / 6); time.sleep(0.1)
        time.sleep(0.4)
        if foto: pg.screenshot(path=F + foto)
        pg.mouse.up(); time.sleep(0.8)
        return pecas(pg)[id]
    r = arrastar('resistor_queimado', 'resistor'); print('resistor queimado:', r['encaixada'], 'voltou para a bandeja:', r['pos']); print('  legenda:', pg.evaluate("() => [...document.querySelectorAll('#app div')].filter(d => d.innerText && /Metal/.test(d.innerText)).map(d => d.className + ': ' + d.innerText).slice(0,2)"))
    time.sleep(1); print('  legenda:', legenda(pg))
    r = arrastar('jumper_curto', 'jumper_vermelho'); print('jumper curto:', r['encaixada'], r['pos'])
    r = arrastar('jumper_vermelho', 'jumper_vermelho', foto='52_oficina_sombra.png'); print('jumper vermelho:', r['encaixada'], r['pos'], alvos['jumper_vermelho'])
    r = arrastar('resistor', 'resistor'); print('resistor:', r['encaixada'])
    r = arrastar('led', 'led'); print('LED (começa virado):', r['encaixada'], 'fixo', r['fixo'], r['pos'], alvos['led'])
    time.sleep(1.5); print('  legenda:', legenda(pg))
    pg.screenshot(path=F + '53_oficina_led_errado.png')
    r = arrastar('led', 'led', virar=1); print('LED virado com F:', r['encaixada'])
    r = arrastar('jumper_preto', 'jumper_preto'); print('jumper preto:', r['encaixada'])
    print('circuito pronto:', J(pg, 'return j.oficina.circuitoPronto'), 'foco:', J(pg, 'return j.oficina.focoPC'))
    pg.screenshot(path=F + '54_oficina_pronta.png')
    print('fim:', pular(pg, 120, lambda: cenas(pg)['oficina_energia']['estado'] == 'terminada'), cenas(pg)['oficina_energia'])
    time.sleep(2.5)
    J(pg, "__t.olharId('motor_engrenagem')"); time.sleep(1.5); pg.screenshot(path=F + '55_oficina_motor.png')
    J(pg, "__t.olharId('protoboard')"); time.sleep(1); pg.screenshot(path=F + '56_oficina_led_aceso.png')
    print('progresso', J(pg, 'return JSON.stringify(j.progresso)'))
    print('falas por evento:', J(pg, 'return j.historicoAvulsas.join(", ")'))
    print('\n'.join(erros[:30]) or 'sem erros')
    b.close()
